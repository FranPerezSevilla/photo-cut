import 'package:flutter/foundation.dart';
import 'package:flutter/widgets.dart';

@immutable
final class PhotoCutLocalizations {
  const PhotoCutLocalizations(this.locale);

  final Locale locale;

  static const List<Locale> supportedLocales = <Locale>[
    Locale('en'),
    Locale('es'),
    Locale('fr'),
    Locale('pt'),
    Locale('de'),
  ];

  static const LocalizationsDelegate<PhotoCutLocalizations> delegate =
      _PhotoCutLocalizationsDelegate();

  static PhotoCutLocalizations of(BuildContext context) {
    return Localizations.of<PhotoCutLocalizations>(
          context,
          PhotoCutLocalizations,
        ) ??
        const PhotoCutLocalizations(Locale('es'));
  }

  Map<String, String> get _strings {
    return _localizedValues[locale.languageCode] ?? _localizedValues['en']!;
  }

  String text(String key) => _strings[key] ?? _localizedValues['en']![key] ?? key;

  String stepLabel(int current, int total, String title) =>
      '${text('step')} $current ${text('of')} $total · $title';

  String copyCount(int count) => count == 1
      ? '1 ${text('copySingular')}'
      : '$count ${text('copyPlural')}';

  String pageSummary(int copies, int pages) => pages == 1
      ? '${copyCount(copies)} · 1 ${text('pageSingular')}'
      : '${text('pageSingular')} 1 ${text('of')} $pages · ${copyCount(copies)}';

  String dpiEstimated(int dpi) => '${text('estimatedResolution')}: ≈ $dpi ppp';

  String zoomDpi(int dpi) => '${text('estimatedQuality')}: $dpi ppp';

  String selectedPhysicalSize(String size) =>
      '${text('upToApprox')} $size ${text('photoQualitySuffix')}';

  String fileLabel(String filename) => '${text('file')}: $filename';
}

final class _PhotoCutLocalizationsDelegate
    extends LocalizationsDelegate<PhotoCutLocalizations> {
  const _PhotoCutLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => PhotoCutLocalizations.supportedLocales.any(
    (Locale supported) => supported.languageCode == locale.languageCode,
  );

  @override
  Future<PhotoCutLocalizations> load(Locale locale) {
    return SynchronousFuture<PhotoCutLocalizations>(
      PhotoCutLocalizations(Locale(locale.languageCode)),
    );
  }

  @override
  bool shouldReload(_PhotoCutLocalizationsDelegate old) => false;
}

